def test_build_smooth_design_dm_matches_R_reference() -> None:
    """``build_smooth_design`` ``dm`` must match the R-side ``r_dm.csv`` cell-by-cell.

    The R reference comes from ``fitGAM(crv, nknots=6, genes=1:5)``.
    """
    if not (R_REF_DIR / "r_dm.csv").exists():
        pytest.skip("R reference r_dm.csv not found")
    if not (R_REF_DIR / "r_ps_seed7.csv").exists():
        pytest.skip("R reference r_ps_seed7.csv not found")
    if not (R_REF_DIR / "r_wsamp_seed7.csv").exists():
        pytest.skip("R reference r_wsamp_seed7.csv not found")

    from tradeseq._design_builder import build_smooth_design
    from tradeseq._knots import find_knots

    ps = np.loadtxt(R_REF_DIR / "r_ps_seed7.csv", delimiter=",", skiprows=1)
    w_samp = np.loadtxt(R_REF_DIR / "r_wsamp_seed7.csv", delimiter=",", skiprows=1)
    r_dm = pd.read_csv(R_REF_DIR / "r_dm.csv")
    n_cells = ps.shape[0]
    U = np.ones((n_cells, 1))
    # tradeSeq fitGAM uses log(counts library size) as the offset by default.
    # The R `dm$"offset(offset)"` column captures the per-cell offset used in the
    # fit; we feed it back into the Python builder to get a bit-exact comparison.
    offset = r_dm["offset(offset)"].to_numpy()
    knots_list = find_knots(6, ps, w_samp)
    design = build_smooth_design(ps, w_samp, U, knots_list, offset)
    # Column order parity
    assert list(design.dm.columns) == list(r_dm.columns)
    # Cell-by-cell parity (the per-cell t/l/U/offset are all positional)
    pd.testing.assert_frame_equal(
        design.dm.reset_index(drop=True),
        r_dm.reset_index(drop=True),
        check_dtype=False,
        atol=1e-12,
    )


def test_build_smooth_design_with_conditions_dm_columns_interleaved() -> None:
    """Conditions-aware dm: ``U, offset(offset), t1, l1_1, ..., l1_K, t2, l2_1, ..., l2_K``.

    R formula (fitGAM.R:282-292) expands each lineage into ``nlevels(conditions)``
    condition-specific smoothers, all anchored on the same ``tj``. The resulting
    ``m$model[, -1]`` interleaves ``tj`` followed by all ``lj_k`` BEFORE moving to
    the next lineage.
    """
    from tradeseq._design_builder import build_smooth_design_with_conditions

    n_cells = 40
    n_lin = 2
    rng = np.random.default_rng(0)
    pseudotime = rng.uniform(0.0, 1.0, size=(n_cells, n_lin))
    w_samp = np.zeros((n_cells, n_lin), dtype=np.float64)
    w_samp[:20, 0] = 1.0
    w_samp[20:, 1] = 1.0
    U = np.ones((n_cells, 1))
    knots = np.linspace(0.0, 1.0, 5)
    knots_list = {f"t{j+1}": knots for j in range(n_lin)}
    offset = np.zeros(n_cells)
    conditions = pd.Categorical(["A"] * (n_cells // 2) + ["B"] * (n_cells // 2))
    design = build_smooth_design_with_conditions(
        pseudotime, w_samp, U, knots_list, offset, conditions
    )
    assert list(design.dm.columns) == [
        "U",
        "offset(offset)",
        "t1",
        "l1_1",
        "l1_2",
        "t2",
        "l2_1",
        "l2_2",
    ]


