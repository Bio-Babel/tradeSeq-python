def test_build_smooth_design_dm_columns_interleaved_2lineage() -> None:
    """``build_smooth_design`` must produce ``dm`` columns in interleaved order.

    R's ``mgcv::gam`` builds ``m$model[, -1]`` from
    ``y ~ -1 + U + s(t1, by=l1) + s(t2, by=l2) + offset(offset)``,
    which materialises columns as ``U, offset(offset), t1, l1, t2, l2``.
    Downstream code (e.g. :mod:`tradeseq._design`'s ``lineageIds + off``
    positional indexing) relies on this layout.
    """
    from tradeseq._design_builder import build_smooth_design

    n_cells = 30
    n_lin = 2
    rng = np.random.default_rng(0)
    pseudotime = rng.uniform(0.0, 1.0, size=(n_cells, n_lin))
    w_samp = np.zeros((n_cells, n_lin), dtype=np.float64)
    w_samp[: n_cells // 2, 0] = 1.0
    w_samp[n_cells // 2:, 1] = 1.0
    U = np.ones((n_cells, 1))
    knots = np.linspace(0.0, 1.0, 5)
    knots_list = {f"t{j+1}": knots for j in range(n_lin)}
    offset = np.zeros(n_cells)
    design = build_smooth_design(pseudotime, w_samp, U, knots_list, offset)
    assert list(design.dm.columns) == [
        "U",
        "offset(offset)",
        "t1",
        "l1",
        "t2",
        "l2",
    ]


