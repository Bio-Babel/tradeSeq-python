def test_wald_test_fc_qr_chol_generalized_agree_full_rank(L_matrices, gene_inputs):
    """For a full-rank L the three matrix-inverse branches must agree numerically."""
    beta, Sigma = gene_inputs[1]
    L = L_matrices["L_full"]
    s_qr, df_qr, p_qr = wald_test_fc(beta, Sigma, L, 0, "QR")
    s_ch, df_ch, p_ch = wald_test_fc(beta, Sigma, L, 0, "Chol")
    s_gn, df_gn, p_gn = wald_test_fc(beta, Sigma, L, 0, "generalized")
    np.testing.assert_allclose([s_qr, s_ch, s_gn], [s_qr, s_qr, s_qr], atol=1e-9)
    assert df_qr == df_ch == df_gn == 2


def test_wald_test_fc_eigen_returns_nan_for_rank1(gene_inputs):
    """The eigen branch returns NaN when L has a single column (effective r==1)."""
    beta, Sigma = gene_inputs[1]
    p = beta.shape[0]
    L1 = np.zeros((p, 1))
    L1[1, 0] = 1.0
    stat, df, pval = wald_test_fc(beta, Sigma, L1, 0, "eigen")
    assert np.isnan(stat) and np.isnan(df) and np.isnan(pval)


def test_wald_test_fc_treat_zeros_stat_when_estimate_below_cutoff(gene_inputs):
    """A large l2fc must shrink the estimate to zero, giving stat=0 and pval=1."""
    beta, Sigma = gene_inputs[1]
    p = beta.shape[0]
    L = np.zeros((p, 1))
    L[1, 0] = 1.0
    stat, df, pval = wald_test_fc(beta, Sigma, L, l2fc=20, inverse="QR")
    assert stat == 0.0
    assert df == 1.0
    assert pval == 1.0


def test_wald_test_fc_invalid_inverse_raises(gene_inputs):
    """An unknown ``inverse`` keyword should fail loudly."""
    beta, Sigma = gene_inputs[1]
    p = beta.shape[0]
    L = np.zeros((p, 1))
    L[1, 0] = 1.0
    with pytest.raises(ValueError, match="Unknown inverse strategy"):
        wald_test_fc(beta, Sigma, L, 0, "nope")


