def test_wald_test_fc_matches_R_for_all_combos(
    L_matrices, gene_inputs, wald_results_ref
):
    """Every (gene, L, inverse, l2fc) row of waldTestFC must match the R dump."""
    for _, row in wald_results_ref.iterrows():
        gene = int(row["gene"])
        L_name = row["L"]
        inverse = row["inverse"]
        l2fc = float(row["l2fc"])
        beta, Sigma = gene_inputs[gene]
        L = L_matrices[L_name]

        stat, df, pval = wald_test_fc(beta, Sigma, L, l2fc=l2fc, inverse=inverse)

        r_stat = row["stat"]
        r_df = row["df"]
        r_pval = row["pval"]
        ctx = f"gene={gene} L={L_name} inverse={inverse} l2fc={l2fc}"

        if np.isnan(r_stat):
            assert np.isnan(stat), f"expected NaN stat, got {stat} @ {ctx}"
            assert np.isnan(df), f"expected NaN df, got {df} @ {ctx}"
            assert np.isnan(pval), f"expected NaN pval, got {pval} @ {ctx}"
        else:
            assert not np.isnan(stat), f"expected finite stat, got NaN @ {ctx}"
            np.testing.assert_allclose(
                stat, r_stat, atol=1e-10, rtol=1e-10, err_msg=f"stat @ {ctx}"
            )
            np.testing.assert_allclose(
                df, r_df, atol=1e-12, err_msg=f"df @ {ctx}"
            )
            np.testing.assert_allclose(
                pval, r_pval, atol=1e-10, rtol=1e-10, err_msg=f"pval @ {ctx}"
            )


